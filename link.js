    // Event listener global untuk semua dropdown
    document.querySelectorAll(".dropdown").forEach(select => {
      select.addEventListener("change", e => {
        const reportType = e.target.dataset.type;
        const selectedUPT = e.target.value;
        const button = document.querySelector(`[data-btn="${reportType}"]`);

        if (selectedUPT && folderLinks[reportType][selectedUPT]) {
          button.href = folderLinks[reportType][selectedUPT];
          button.classList.remove("opacity-50", "pointer-events-none");
          button.textContent = "Buka Folder UPT";
        } else {
          button.href = "#";
          button.classList.add("opacity-50", "pointer-events-none");
          button.textContent = "Lihat Folder";
        }
      });
    });